def get_device_catalog() -> List[Dict[str, Any]]:
    """Returns the complete list of all supported OpenRazer input devices."""
    return RAZER_DEVICE_CATALOG


def _norm_name(s: str) -> str:
    return "".join(c for c in s.lower() if c.isalnum())


def get_device_by_name(name: str) -> Optional[Dict[str, Any]]:
    """Finds a device by its exact, fuzzy, or normalized matching name."""
    name_norm = _norm_name(name)
    if not name_norm:
        return None
    # 1. Exact normalized match
    for d in RAZER_DEVICE_CATALOG:
        if _norm_name(d["name"]) == name_norm or _norm_name(d.get("class", "")) == name_norm:
            return d
    # 2. Substring normalized match
    for d in RAZER_DEVICE_CATALOG:
        d_norm = _norm_name(d["name"])
        if name_norm in d_norm or d_norm in name_norm:
            return d
    return None



def get_device_by_pid(pid: int) -> Optional[Dict[str, Any]]:
    """Finds a device by its USB product ID integer or hex."""
    for d in RAZER_DEVICE_CATALOG:
        if d.get("pid_int") == pid:
            return d
    return None


def get_archetype_for_device(device_name: str) -> str:
    """Resolves the appropriate hardware layout archetype for any device name."""
    nl = (device_name or "").lower()

    # If the user explicitly requested a specific variant (e.g. TKL, Hex, Mini),
    # prioritize the explicit qualifier before falling back to base model match.
    if "tkl" in nl or "tournament" in nl or "tenkeyless" in nl:
        return KEYBOARD_TKL
    if "mini" in nl or " 60" in nl or "60%" in nl:
        return KEYBOARD_60
    if "naga hex" in nl or "trinity hex" in nl or "hex v2" in nl or "hex" in nl:
        return MOUSE_NAGA_HEX
    if "tartarus" in nl:
        return KEYPAD_TARTARUS
    if "orbweaver" in nl:
        return KEYPAD_ORBWEAVER
    if "nostromo" in nl:
        return KEYPAD_NOSTROMO

    dev = get_device_by_name(device_name)
    if dev:
        return dev["archetype"]
    
    # Heuristic fallback if unknown device

    if "naga hex" in nl or "trinity hex" in nl:
        return MOUSE_NAGA_HEX
    if "naga" in nl:
        return MOUSE_NAGA_MMO
    if "basilisk" in nl:
        return MOUSE_BASILISK_FPS
    if "viper" in nl or "ouroboros" in nl or "taipan" in nl or "lancehead" in nl:
        return MOUSE_AMBI
    if "mouse" in nl or "deathadder" in nl or "mamba" in nl or "cobra" in nl or "abyssus" in nl or "orochi" in nl:
        return MOUSE_FPS
    if "mini" in nl or "60" in nl:
        return KEYBOARD_60
    if "tkl" in nl or "tournament" in nl or "tenkeyless" in nl:
        return KEYBOARD_TKL
    if "blade" in nl:
        return KEYBOARD_BLADE
    return KEYBOARD_FULL


def list_devices_by_category(category: str) -> List[Dict[str, Any]]:
    """Filters devices by category: 'keypad', 'keyboard', 'mouse', or 'laptop'."""
    cat_low = category.strip().lower()
    return [d for d in RAZER_DEVICE_CATALOG if d["category"].lower() == cat_low]
